/* Look up a placement and resolve it to a concrete asset. Returns
   null for an unknown or deliberately empty slot. */
export function resolve(slot) {
  const p = PLACEMENTS[slot];
  if (!p) return null;
  const asset = ASSETS[p.asset];
  if (!asset) return null;
  return { ...asset, loops: p.loops ?? 2, size: p.size || 'md', slot };
}

/* Direct access for code that needs a specific file rather than a
   placement - the games drawing into canvas, mostly. */
export const asset = (name) => ASSETS[name] || null;
