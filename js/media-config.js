/* ============================================================
   MEDIA CONFIGURATION

   Every external asset path on the site is declared here, and
   nowhere else. js/media.js renders these; it never names a file.

   Personal photographs and video are NOT here - they live in
   js/assets.js and always have. Splitting them across two files
   would be exactly the scattering this module exists to prevent.

   ------------------------------------------------------------
   FORMATS

   The supplied GIFs totalled ~58 MB. None used transparency, so
   they are converted to MP4 by tools/build-external.sh and come
   out around 20x smaller - 3.7 MB for the whole library. A GIF is
   256 colours decoded frame-by-frame on the CPU; an MP4 keeps
   full colour and is decoded by video hardware.

   The cut-outs stay as WebP-with-alpha, because their transparent
   background is the entire point: the hookah has to stand on the
   game's own backdrop, the diving objects have to sit in water.

   ------------------------------------------------------------
   MISSING FILES ARE FINE

   Any slot may point at a file that does not exist, or be set to
   null. The element removes itself, leaving no gap and no broken
   image icon. Decorative media can never break a section.
   ============================================================ */

